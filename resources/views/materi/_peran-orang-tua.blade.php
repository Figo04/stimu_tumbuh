    <p class="mb-2">Orang tua memiliki peran penting dalam mendukung perkembangan pada setiap tahapan usia.</p>
    <ul class="list-disc space-y-1 pl-5">
        <li><span class="font-medium">Memberikan lingkungan yang aman.</span> Anak membutuhkan ruang untuk bergerak dan bereksplorasi.</li>
