        <li><span class="font-medium">Memberikan komunikasi yang responsif.</span> Orang tua perlu mendengarkan, merespons, dan berinteraksi dengan anak.</li>
        <li><span class="font-medium">Memantau perkembangan anak.</span> Orang tua perlu memperhatikan kemajuan dan perubahan kemampuan anak.</li>
        <li><span class="font-medium">Menghindari tekanan berlebihan.</span> Setiap anak memiliki kecepatan perkembangan yang berbeda. Stimulasi sebaiknya dilakukan secara menyenangkan.</li>
    </ul>
</x-tip-box>
