<x-highlight judul="Apa itu perkembangan bahasa?">
    Perkembangan bahasa adalah proses anak memahami dan menggunakan simbol komunikasi, baik melalui suara, kata, gestur, maupun ekspresi. Bahasa terdiri atas dua kemampuan utama:
    <ul class="mt-2 list-disc space-y-1 pl-5">
        <li><span class="font-medium">Bahasa reseptif:</span> kemampuan memahami bahasa yang didengar.</li>
        <li><span class="font-medium">Bahasa ekspresif:</span> kemampuan menyampaikan keinginan, pikiran, atau perasaan melalui suara, kata, dan gestur.</li>
    </ul>
</x-highlight>

<h3 class="mt-6 mb-2 text-lg font-semibold text-gray-900">Meniru 2–3 kata sederhana</h3>
<p>Pada usia 12 bulan, anak mulai belajar berkomunikasi melalui suara dan kata-kata sederhana. Salah satu kemampuan yang dapat distimulasi adalah kemampuan anak untuk meniru 2 sampai 3 kata yang sering didengar dalam kehidupan sehari-hari, seperti mama, papa, atau nenek.</p>

<x-langkah-stimulasi judul="Pelaksanaan stimulasi" :langkah="[
    'Orang tua dapat melakukan stimulasi dengan mengajak anak berbicara secara langsung. Posisikan wajah orang tua sejajar dengan wajah anak agar anak dapat melihat gerakan bibir dan ekspresi wajah dengan jelas.',
    'Sebutkan satu kata sederhana secara perlahan dan jelas, misalnya “Mama”. Kemudian berikan kesempatan kepada anak untuk memperhatikan dan menirukannya.',
    'Selanjutnya, orang tua dapat mengucapkan kata “Papa” atau “Nenek”. Ulangi kata tersebut beberapa kali dalam suasana yang menyenangkan. Gunakan ekspresi wajah yang ceria dan berikan pujian ketika anak mencoba menirukan suara atau kata tersebut.',
]" />

<x-highlight varian="penting" judul="Tidak perlu memaksa">
    Tidak perlu memaksa anak untuk langsung mengucapkan kata dengan sempurna. Setiap usaha anak untuk meniru suara merupakan bagian dari proses belajar.
</x-highlight>

<p class="mt-6 mb-2 font-semibold">Contoh interaksi</p>
<div class="space-y-1 rounded-lg bg-gray-50 p-4">
    <p><span class="font-medium">Orang tua:</span> “Mama… coba bilang Mama.”</p>
    <p><span class="font-medium">Anak:</span> “Ma… ma.”</p>
    <p><span class="font-medium">Orang tua:</span> “Pintar! Mama.”</p>
    <p class="text-gray-600">Kemudian orang tua dapat melanjutkan dengan “Papa…” atau “Nenek…” dan memberikan kesempatan kepada anak untuk menirukannya.</p>
</div>

